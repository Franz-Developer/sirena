Si me indicas si tu sistema es:

Facturación Electrónica en Línea (SIAT actual), o
Facturación Computarizada antigua con dosificación,

puedo explicarte exactamente qué debes generar y darte un ejemplo.

1. Obtener el CUIS

El sistema solicita al SIN un Código Único de Inicio de Sistemas (CUIS) para identificar la sucursal y punto de venta.

Sistema → SIAT → Solicitud CUIS
SIAT → Sistema → Código CUIS

El CUIS suele tener vigencia de varios meses.

2. Obtener el CUFD

Antes de emitir facturas, el sistema solicita un Código Único de Facturación Diaria (CUFD).

Sistema → SIAT → Solicitud CUFD
SIAT → Sistema → CUFD + Código de Control

El CUFD cambia normalmente cada día y es válido para una sucursal y punto de venta específicos.

Ejemplo:

CUFD = EFD7A8B9C123456789...
3. Generar el CUF

El CUF (Código Único de Factura) identifica de forma única cada factura.

Se construye usando datos como:

NIT del emisor
Fecha y hora de emisión
Código de sucursal
Modalidad
Tipo de emisión
Tipo de factura
Documento sector
Número de factura
Punto de venta

Luego se aplica el algoritmo definido por el SIN y se agrega un dígito de control (Módulo 11).

Ejemplo:

CUF =
7D4F1A6B8C9D01234567890ABCDE1234567890ABCDE12345

Normalmente no lo escribes manualmente; tu sistema lo genera automáticamente.

4. Construir el XML

La factura se convierte al formato XML exigido por el SIN.

Ejemplo simplificado:

<facturaElectronicaCompraVenta>
    <cabecera>
        <nitEmisor>1023456789</nitEmisor>
        <razonSocialEmisor>FARMACIA XYZ</razonSocialEmisor>
        <numeroFactura>125</numeroFactura>
        <cuf>...</cuf>
        <cufd>...</cufd>
    </cabecera>
</facturaElectronicaCompraVenta>
5. Firmar digitalmente el XML

El XML debe firmarse con el certificado digital autorizado para la empresa.

XML → Firma Digital → XML Firmado

La firma garantiza autenticidad e integridad.

6. Enviar la factura al SIAT

El XML firmado se envía mediante los servicios web del SIN.

Sistema → SIAT → XML Firmado
SIAT → Sistema → Recepción

Si todo está correcto, el SIN devuelve:

Código Recepción
Transacción = TRUE
